/**
 * Generate the published rule counts from the rule catalog.
 *
 * Seven public surfaces used to state a rule count by hand. They drifted apart
 * from the engine and from each other — README said 131 while the catalog held
 * 143 and the repo description said 140+ — and the README's category table
 * listed twelve categories that do not exist, summing to a third number again.
 *
 * `package.json` had the same problem and was fixed by REMOVING the claim. These
 * surfaces genuinely want to state a count, so instead the count is generated:
 * each region is delimited by markers and rewritten from rule-catalog.json,
 * which `build-catalog.mjs` derives from RULE_CATALOG at build time.
 *
 * Usage:
 *   node scripts/sync-rule-counts.mjs           rewrite the blocks in place
 *   node scripts/sync-rule-counts.mjs --check   exit 1 if any block is stale
 *
 * `--check` is what CI runs, so a hand-edited count or a catalog change that
 * skips the docs fails the build instead of shipping.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const catalog = JSON.parse(await readFile(resolve(repoRoot, 'rule-catalog.json'), 'utf-8'));

const total = catalog.total;
const pattern = catalog.rules.filter((r) => r.source === 'pattern').length;
const ai = catalog.rules.filter((r) => r.source === 'ai').length;

/**
 * The five canonical categories, in the order `CategoryEnum` declares them.
 * There are exactly five, enforced by a module-load gate in rules/catalog.ts;
 * any other list is fiction.
 */
const CATEGORY_LABELS = [
  ['phi-exposure', 'PHI Exposure', 'SSN/MRN in code, PHI in logs, localStorage, URLs, diagnosis codes, unencrypted patient data'],
  ['encryption', 'Encryption', 'Weak crypto (MD5, DES, RC4), disabled SSL/TLS, HTTP URLs, missing at-rest encryption, credential exposure'],
  ['access-control', 'Access Control', 'SQL injection, XSS, CORS wildcards, hardcoded credentials, missing auth, RBAC gaps, MFA, session control, HIPAA 2026 NPRM checks'],
  ['audit-logging', 'Audit Logging', 'Missing logging framework, unlogged PHI operations, PHI in error output, insecure configuration'],
  ['data-retention', 'Data Retention', 'Bulk deletes without audit, missing retention policies, improper deletion, backup gaps'],
];

const counts = catalog.counts;
const categorySum = CATEGORY_LABELS.reduce((n, [key]) => n + (counts[key] ?? 0), 0);
if (categorySum !== total) {
  throw new Error(
    `[sync-rule-counts] category counts sum to ${categorySum} but the catalog total is ${total}. ` +
    `A category is missing from CATEGORY_LABELS.`,
  );
}

const summary = `${total} rules (${pattern} pattern-based + ${ai} AI-powered)`;

const categoryTable = [
  '| Category | Rules | What it detects |',
  '|----------|-------|-----------------|',
  ...CATEGORY_LABELS.map(([key, label, detects]) => `| **${label}** | ${counts[key]} | ${detects} |`),
  `| **Total** | **${total}** | ${pattern} pattern-based + ${ai} AI-powered |`,
].join('\n');

/** Each block: file, marker id, comment syntax, and the generated body. */
const BLOCKS = [
  { file: 'README.md', id: 'rule-count-lead', style: 'md',
    body: `**Automated security scanning for healthcare applications.** ${total} detection rules that catch PHI exposures, missing encryption, and access control gaps before they reach production. HIPAA 2026 ready - 15/15 requirements covered.` },
  { file: 'README.md', id: 'rule-count-features', style: 'md',
    body: `- **${total} detection rules** (${pattern} pattern-based + ${ai} AI-powered) across 5 HIPAA categories (PHI exposure, encryption, access control, audit logging, data retention)` },
  { file: 'README.md', id: 'rule-count-pricing', style: 'md',
    body: `| **Open Source** | **$0/forever** | Full scanner, CLI, ${total} rules, compliance scoring, training module, community support |` },
  { file: 'README.md', id: 'rule-count-categories', style: 'md',
    body: `vlayer scans for **${summary}** across 5 HIPAA compliance categories:\n\n${categoryTable}` },
  { file: 'docs/start-here.md', id: 'rule-count-intro', style: 'md',
    body: `vlayer checks your code against ${summary} across the 5 HIPAA compliance categories:` },
  { file: 'dashboard/app/page.tsx', id: 'rule-count-cli', style: 'jsx',
    body: `              <p className="text-xs text-slate-400 mb-3">${total} rules. Scan any directory from your terminal.</p>` },
];

function markers(style, id) {
  return style === 'jsx'
    ? [`{/* vlayer:${id}:start — generated by scripts/sync-rule-counts.mjs, do not edit */}`,
       `{/* vlayer:${id}:end */}`]
    : [`<!-- vlayer:${id}:start — generated by scripts/sync-rule-counts.mjs, do not edit -->`,
       `<!-- vlayer:${id}:end -->`];
}

const stale = [];
const byFile = new Map();
for (const block of BLOCKS) {
  if (!byFile.has(block.file)) byFile.set(block.file, await readFile(resolve(repoRoot, block.file), 'utf-8'));
  let text = byFile.get(block.file);
  const [open, close] = markers(block.style, block.id);

  const start = text.indexOf(open);
  const end = text.indexOf(close);
  if (start === -1 || end === -1) {
    throw new Error(`[sync-rule-counts] markers for "${block.id}" not found in ${block.file}`);
  }

  const current = text.slice(start + open.length, end);
  const desired = `\n${block.body}\n`;
  if (current !== desired) {
    stale.push(`${block.file} :: ${block.id}`);
    text = text.slice(0, start + open.length) + desired + text.slice(end);
    byFile.set(block.file, text);
  }
}

if (CHECK) {
  if (stale.length > 0) {
    console.error('\n[sync-rule-counts] STALE generated rule-count blocks:\n');
    for (const s of stale) console.error(`  ${s}`);
    console.error(
      `\nThe catalog holds ${summary}. Run \`npm run build\` and commit the result.` +
      `\nDo not hand-edit these blocks — they are generated from rule-catalog.json.\n`,
    );
    process.exit(1);
  }
  console.log(`[sync-rule-counts] all ${BLOCKS.length} generated blocks are current (${summary}).`);
} else {
  for (const [file, text] of byFile) {
    await writeFile(resolve(repoRoot, file), text);
  }
  const label = stale.length === 0 ? 'already current' : `updated ${stale.length}`;
  console.log(`[sync-rule-counts] ${label} — ${summary}`);
}
